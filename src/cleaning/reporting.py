    ("products.product_photos_qty", "Photo metadata is absent; underlying cause is unknown.", "Retain nullable integer; missing does not establish that the product has no photos."),
    ("products.product_weight_g", "Physical metadata is absent; underlying cause is unknown.", "Retain NULL; do not impute a median or substitute zero. Populated zero weights are retained and flagged separately."),
